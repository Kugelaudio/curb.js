import { join } from "node:path";
import { RENDER_CHECK_ARG } from "./render-check.js";

/**
 * The source of the entry `curb build` generates into `.curb/build/`.
 *
 * Pure string builders: every path they embed is passed in, so a test can read the
 * generated text without running a build.
 */

/**
 * The worker-mode job body of the generated `hosted-worker.mjs`.
 *
 * Its own constant so a test can run exactly this text against stand-ins, without a
 * build. It is `curb start`'s job: `runVoiceWorkerJob` (`server/voice/livekit-host/worker.ts`)
 * serves the dispatched call the way every other route does. It uses `defineAgent` and
 * `runVoiceWorkerJob`, which the generated entry imports.
 */
export const HOSTED_WORKER_JOB_SOURCE = [
  "export default defineAgent({",
  "  entry: (ctx) => runVoiceWorkerJob(ctx),",
  "});",
].join("\n");

/**
 * The RUNNABLE entry, `hosted-worker.mjs`.
 *
 * `curb start` registers the framework's worker module through tsx, and a hosted artifact
 * has no tsx -- so the artifact needs its own entry that boots from the bundled agent. Its
 * worker mode runs the SAME job.
 *
 * It asserts its credentials before touching LiveKit, so a misconfigured deployment
 * fails with the missing variable named rather than inside the agents runtime.
 *
 * Three modes, chosen by the environment and never more than one:
 *
 *   - MANAGED (CURB_MANAGEMENT_ADDR): the host starts the process before any call and
 *     hands it calls over a TCP management port, or with CURB_RUNNER_ROLE=hooks hands it
 *     the agent's hooks and no call. See bundler/managed-runner.ts.
 *   - DIRECT JOIN (CURB_REALTIME_URL + CURB_REALTIME_TOKEN): a hosted platform already
 *     created the room and minted this runner a room-scoped token, so the artifact
 *     joins that one room and serves that one call. See bundler/direct-join.ts.
 *   - WORKER/DISPATCH (otherwise): register a worker pool with the LiveKit API key and
 *     secret under `curb start`'s name, wait to be dispatched, and serve each call with
 *     `curb start`'s own job.
 *
 * The branch is an if/else around the WHOLE worker path rather than a guard inside it:
 * LIVEKIT_API_KEY and LIVEKIT_API_SECRET must be unreachable in direct-join mode, and
 * direct-join deletes them from the environment on entry so no dependency can read
 * them either.
 */
export function workerEntrySource(paths: {
  contextRegistryPath: string;
  registryPath: string;
  /** The framework's own `src/`, which the entry imports from directly. */
  frameworkSrc: string;
  /** `@livekit/agents` as resolved from the framework, not from the project. */
  livekitAgentsEntry: string;
  /** The project's package name, baked in so worker mode registers as `curb start` does. */
  projectName?: string;
}): string {
  const { contextRegistryPath, registryPath, frameworkSrc, livekitAgentsEntry, projectName } = paths;
  return [
    "// Generated by `curb build`. Do not edit.",
    // First, so the markdown is installed before any agent module can render.
    `import ${JSON.stringify(contextRegistryPath)};`,
    `import { defineAgent } from ${JSON.stringify(join(frameworkSrc, "orchestration.ts"))};`,
    `import { setBundledAgentRegistry } from ${JSON.stringify(join(frameworkSrc, "agent-registry.node.ts"))};`,
    `import * as registry from ${JSON.stringify(registryPath)};`,
    `import { runVoiceWorkerJob } from ${JSON.stringify(join(frameworkSrc, "server", "voice", "livekit-host", "worker.ts"))};`,
    `import { voiceWorkerAgentName } from ${JSON.stringify(join(frameworkSrc, "server", "voice", "worker-name.ts"))};`,
    `import { runHostedRenderCheck } from ${JSON.stringify(join(frameworkSrc, "bundler", "render-check.ts"))};`,
    `import { readDirectJoinConfig, runHostedDirectJoin } from ${JSON.stringify(join(frameworkSrc, "bundler", "direct-join.ts"))};`,
    `import { readManagedConfig, runManaged } from ${JSON.stringify(join(frameworkSrc, "bundler", "managed-runner.ts"))};`,
    `import { cli, ServerOptions } from ${JSON.stringify(livekitAgentsEntry)};`,
    `import { fileURLToPath as __curbFileURLToPath2 } from "node:url";`,
    "",
    "",
    "// Install the static registry BEFORE anything reads an agent: a hosted artifact",
    "// has no src/agent/ to walk and no TypeScript loader to import .tsx with. This",
    "// must also run in LiveKit's FORKED job process, which imports this module fresh,",
    "// so it lives at module scope rather than inside the worker start path.",
    "setBundledAgentRegistry(registry);",
    "",
    "// Self-check mode, run by `curb build` against the finished artifact. It lives in",
    "// THIS file rather than a second entry point so that what renders is the module",
    "// graph the runner actually executes -- a sibling entry could carry context this",
    "// one is missing and report a green build for an empty agent.",
    `if (process.argv.includes(${JSON.stringify(RENDER_CHECK_ARG)})) {`,
    "  const report = await runHostedRenderCheck();",
    "  process.exit(report.errors.length > 0 ? 1 : 0);",
    "}",
    "",
    "// READINESS PROBE. A hosted platform asks a candidate deployment to prove it LOADS",
    "// before any caller reaches it: import the bundle, construct the agent, exit, and never",
    "// touch media. The platform deliberately hands a probe neither a room nor LiveKit",
    "// credentials, because a probe given a room would join it and the deployment would be",
    "// paying for media on a call with no human on it.",
    "//",
    "// It reuses the SAME check `curb build` runs against the finished artifact, for exactly",
    "// the reason that check lives in this file: what loads has to be the module graph the",
    "// runner actually executes. A separate probe path could pass while the real one fails.",
    "//",
    "// Checked BEFORE readDirectJoinConfig, because 'no room and no API keys' is a",
    "// configuration error in every other mode and would exit 78 before reaching here.",
    'if (process.env.CURB_READINESS_PROBE === "1") {',
    "  try {",
    "    const report = await runHostedRenderCheck();",
    "    if (report.errors.length > 0) {",
    "      for (const message of report.errors) console.error(`curb: ${message}`);",
    "      process.exit(1);",
    "    }",
    "  } catch (error) {",
    "    const detail = error instanceof Error ? (error.stack ?? error.message) : String(error);",
    "    console.error(`curb: the bundle did not load: ${detail}`);",
    "    process.exit(70); // EX_SOFTWARE",
    "  }",
    '  console.log("curb: readiness probe passed; the bundle imported and the agent constructed");',
    "  process.exit(0);",
    "}",
    "",
    "// MANAGED mode first: the host starts the process and hands it calls over a TCP",
    "// management port (CURB_MANAGEMENT_ADDR) afterwards, so one runner serves several",
    "// conversations of one generation. Checked before direct-join because a managed",
    "// runner is given no room at start -- there is nothing for readDirectJoinConfig to",
    "// find, and the absence is correct rather than a misconfiguration.",
    "//",
    "// A CURB_RUNNER_ROLE that names no role, or a hook runner with no management port, is a",
    "// configuration error, never a quiet fall through to the modes below.",
    "let __curbManaged = null;",
    "try {",
    "  __curbManaged = readManagedConfig();",
    "} catch (error) {",
    "  console.error(`curb: ${error instanceof Error ? error.message : String(error)}`);",
    "  process.exit(78); // EX_CONFIG",
    "}",
    "if (__curbManaged) {",
    "  try {",
    "    await runManaged(__curbManaged);",
    "  } catch (error) {",
    "    console.error(`curb: ${error instanceof Error ? (error.stack ?? error.message) : String(error)}`);",
    "    process.exit(70); // EX_SOFTWARE",
    "  }",
    "  process.exit(0);",
    "}",
    "",
    "// Which mode this runner is in. A half-configured direct join is an error, never a",
    "// quiet fall back to the worker path -- see readDirectJoinConfig.",
    "let __curbDirect = null;",
    "try {",
    "  __curbDirect = readDirectJoinConfig();",
    "} catch (error) {",
    "  console.error(`curb: ${error instanceof Error ? error.message : String(error)}`);",
    "  process.exit(78); // EX_CONFIG",
    "}",
    "",
    "if (__curbDirect) {",
    "  // Direct join: one room, one call, no LiveKit API credentials anywhere in here.",
    "  try {",
    "    await runHostedDirectJoin(__curbDirect);",
    "  } catch (error) {",
    "    console.error(`curb: ${error instanceof Error ? (error.stack ?? error.message) : String(error)}`);",
    "    process.exit(70); // EX_SOFTWARE",
    "  }",
    "  // The call is over. Exit explicitly rather than letting the loop drain: rtc-node",
    "  // holds native handles whose lifetime is not ours to reason about, and a runner",
    "  // that lingers past its call keeps the platform's slot occupied.",
    "  process.exit(0);",
    "} else {",
    "  const required = [\"LIVEKIT_URL\", \"LIVEKIT_API_KEY\", \"LIVEKIT_API_SECRET\"];",
    "  const missing = required.filter((name) => !process.env[name]);",
    "  if (missing.length > 0) {",
    "    console.error(",
    "      `curb: cannot start the voice worker, missing ${missing.join(\", \")}. ` +",
    "        `Set them in the deployment's environment, or set CURB_REALTIME_URL and ` +",
    "        `CURB_REALTIME_TOKEN to join one already-created room instead.`,",
    "    );",
    "    process.exit(78); // EX_CONFIG",
    "  }",
    "",
    "  // CURB_AGENT_NAME, else the project's package name (baked in by `curb build`), else",
    "  // curb-agent: the name `curb start` registers under.",
    `  const agentName = voiceWorkerAgentName(process.env, ${JSON.stringify(projectName ?? "")});`,
    "  // A filesystem PATH, not import.meta.url. LiveKit forks one child process per",
    "  // job and passes this through as an argument; the child resolves it against its",
    "  // cwd, so a file:// URL becomes <cwd>/file:/... and the fork dies with",
    "  // ERR_MODULE_NOT_FOUND before it can initialize.",
    "  const __curbAgentPath = __curbFileURLToPath2(import.meta.url);",
    "  cli.runApp(new ServerOptions({",
    "    agent: __curbAgentPath,",
    "    agentName,",
    "  }));",
    "}",
    "",
    HOSTED_WORKER_JOB_SOURCE,
  ].join("\n");
}
