import { resolveContextDir } from "../project.node.js";
import { listMarkdownIn, readPublicMarkdownTree } from "../public-context.node.js";

/**
 * Inlines the project's `context/` markdown into the bundle.
 *
 * The runtime reads that directory relative to `AGENT_PROJECT_DIR` or the working
 * directory (`public-context.node.ts`), which a hosted artifact has neither of: the
 * platform starts it from an arbitrary directory outside any curb project. Nothing
 * carried the markdown into the artifact, so `<Text src="policy/coverage-basics.md">`
 * rendered against an empty cache and the agent connected to a room with nothing to say.
 *
 * Inlining rather than copying the files in, for the same reason the skill sources
 * travel through `?raw`: content in the module graph needs no root, and a root is the
 * thing the artifact cannot know. `@vercel/nft` cannot find these on its own — it traces
 * JavaScript imports, and these are read by path at runtime.
 */
export function generateContextRegistryCode(projectRoot: string, publicContextModule: string): string {
  const files = readPublicMarkdownTree(resolveContextDir(projectRoot));

  const entries = Object.entries(files).map(
    ([src, content]) => `  ${JSON.stringify(src)}: ${JSON.stringify(content)},`,
  );

  return [
    "// Generated by `curb build`. Do not edit.",
    `import { setBundledPublicMarkdown } from ${JSON.stringify(publicContextModule)};`,
    "",
    // A side effect at module scope, so importing this module IS installing the context.
    // Both generated entries import it; the one the runner executes cannot end up with a
    // registry the other one has.
    "setBundledPublicMarkdown({",
    ...entries,
    "});",
    "",
  ].join("\n");
}

/** The markdown the artifact is expected to carry, for the build's own verification. */
export function projectContextFiles(projectRoot: string): string[] {
  return listMarkdownIn(resolveContextDir(projectRoot));
}
